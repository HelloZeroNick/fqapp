// Guards for the OHOS file-picker channels.
//
// A MethodChannel with no platform handler fails indistinguishably from a
// broken feature (the Dart side throws MissingPluginException, or a PlatformException
// the UI renders as "导出失败"), so the contract between the Dart service and
// the ArkTS plugin is pinned here: channel name, method names, and the fact that
// the plugin actually reaches the engine.
//
// Run with: node --test test/ohos_file_channel_contracts_test.cjs

'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');

const appDir = path.resolve(__dirname, '..');
const pluginDir = path.join('ohos', 'entry', 'src', 'main', 'ets', 'plugins');
const abilityPath = path.join(
  'ohos',
  'entry',
  'src',
  'main',
  'ets',
  'entryability',
  'EntryAbility.ets',
);

function read(relative) {
  return fs.readFileSync(path.join(appDir, relative), 'utf8');
}

function readPlugin(name) {
  const relative = path.join(pluginDir, name);
  assert.ok(fs.existsSync(path.join(appDir, relative)), `${relative} must exist`);
  return read(relative);
}

test('the TXT export plugin serves fqapp/downloads', () => {
  const source = readPlugin('TxtExportPlugin.ets');
  // The contract with lib/services/book_txt_export.dart.
  assert.ok(source.includes("'fqapp/downloads'"), 'channel name must match the Dart side');
  assert.ok(source.includes("'saveText'"), 'must handle saveText');
  assert.ok(
    source.includes('public: true'),
    'every OHOS save target is user-picked, so it is public',
  );
  // Cancelling must not look like a successful write: Dart turns any error into
  // "导出失败", which is the honest report for a file that was never written.
  assert.ok(
    source.includes("DOWNLOADS_CANCELED"),
    'a cancelled save dialog must not report success',
  );
});

test('the local book picker plugin serves fqapp/local_books', () => {
  const source = readPlugin('LocalBookPickerPlugin.ets');
  // The contract with lib/services/imported_book_store.dart pickBookFile().
  assert.ok(source.includes("'fqapp/local_books'"), 'channel name must match the Dart side');
  assert.ok(source.includes("'pickBookFile'"), 'must handle pickBookFile');
  // Dart requires all three keys, and treats a .txt without decoded text as
  // unreadable — the BOM/GB18030 fallback is what keeps Chinese TXT books
  // importable.
  for (const key of ['name:', 'byteLength:', 'text:', 'bytes:']) {
    assert.ok(source.includes(key), `the reply must carry ${key}`);
  }
  assert.ok(source.includes('gb18030'), 'TXT decoding needs the GB18030 fallback');
  assert.ok(
    source.includes('32 * 1024 * 1024'),
    'the 32 MB ceiling must match Android',
  );
});

test('imported fonts are copied whole, not one buffer from the start', () => {
  const source = readPlugin('ReaderDevicePlugin.ets');
  // A truncated copy still passes the TTF magic-number check and only fails much
  // later inside the engine's typeface parser, which surfaces as "字体无法读取".
  // Reading and writing without an explicit position keeps the file cursor
  // moving; { offset: 0 } on every iteration re-reads chunk 0 forever.
  const copy = source.slice(source.indexOf('private copyFile('));
  assert.ok(copy.length > 0, 'copyFile must exist');
  assert.ok(
    !/fs\.readSync\([^)]*\{\s*offset:\s*0/.test(copy),
    'copyFile must not restart every read at offset 0',
  );
  assert.ok(
    copy.includes('FONT_COPY_SHORT'),
    'a short copy must fail loudly instead of returning a broken font',
  );
  // Registration: the picker works, so a missing channel is never the cause here.
  const ability = read(abilityPath);
  assert.ok(ability.includes('new ReaderDevicePlugin()'), 'EntryAbility must attach ReaderDevicePlugin');
});

test('both file plugins are registered with the engine', () => {
  const ability = read(abilityPath);
  for (const ctor of ['new TxtExportPlugin()', 'new LocalBookPickerPlugin()']) {
    assert.ok(ability.includes(ctor), `EntryAbility must attach ${ctor}`);
  }

  // GeneratedPluginRegistrant.ets is generated by the Flutter tool and must not
  // be edited, so registration has to happen in the ability.
  const registrant = read(path.join(pluginDir, 'GeneratedPluginRegistrant.ets'));
  for (const name of ['TxtExportPlugin', 'LocalBookPickerPlugin']) {
    assert.ok(!registrant.includes(name), 'the generated registrant must not be hand-edited');
  }
});